<script>
  import { generatePinCode } from '$lib/engine/codegen.js'
  import { generateWokwiDiagram } from '$lib/engine/wokwi.js'
  import { MCU_PINS } from '$lib/data/mcu-pins.js'

  export let show = false
  export let components = []
  export let wires = []
  export let projectName = 'CircuitCraft_Firmware'

  let activeTab = 'arduino' // 'arduino' | 'espidf' | 'python' | 'rust' | 'platformio' | 'wokwi'
  let baudRate = '115200'
  let includeWifiBle = true
  let includeFreeRtos = true
  let includeI2cScanner = true
  let includePwmAdc = true
  let copied = false

  // Detect Primary MCU
  $: primaryMcu = detectPrimaryMcu(components)

  function detectPrimaryMcu(comps) {
    if (!comps || comps.length === 0) return { id: 'generic', name: 'Microcontroller Generic', type: 'Generic' }
    const mcu = comps.find(c => c.isMCU || c.type === 'mcu' || MCU_PINS[c.id])
    if (mcu) return mcu
    return { id: 'esp32s3', name: 'ESP32-S3 DevKit', type: 'ESP32' }
  }

  // Base code generation from engine
  $: baseCode = generatePinCode(components, wires, projectName)

  // Rich Multi-Platform Firmware Generators
  $: activeCode = generateTargetCode(activeTab, components, wires, primaryMcu, baudRate, includeWifiBle, includeFreeRtos, includeI2cScanner, includePwmAdc)

  function generateTargetCode(tab, comps, wrs, mcu, baud, wifi, rtos, i2cScan, pwm) {
    const cleanProj = (projectName || 'CircuitCraft').replace(/[^a-zA-Z0-9_]/g, '_')
    const safeBaud = parseInt(baud, 10) || 115200

    if (tab === 'arduino') {
      return generateArduinoCode(cleanProj, comps, wrs, mcu, safeBaud, wifi, i2cScan, pwm)
    } else if (tab === 'espidf') {
      return generateEspIdfCode(cleanProj, comps, wrs, mcu, safeBaud, rtos)
    } else if (tab === 'python') {
      return generateMicroPythonCode(cleanProj, comps, wrs, mcu, safeBaud, wifi, i2cScan)
    } else if (tab === 'rust') {
      return generateRustEmbeddedCode(cleanProj, comps, wrs, mcu, safeBaud)
    } else if (tab === 'platformio') {
      return generatePlatformIoIni(cleanProj, mcu, safeBaud)
    } else if (tab === 'wokwi') {
      const wokwi = generateWokwiDiagram(comps, wrs, projectName)
      return JSON.stringify(wokwi, null, 2)
    }
    return '// Target firmware code'
  }

  function generateArduinoCode(proj, comps, wrs, mcu, baud, wifi, i2cScan, pwm) {
    let s = `/**\n * ====================================================================\n`
    s += ` * Project      : ${proj}\n`
    s += ` * Architecture : ${mcu.name || 'Arduino / ESP32 Architecture'}\n`
    s += ` * Generated By : CircuitCraft Next-Gen EDA Suite\n`
    s += ` * Timestamp    : ${new Date().toISOString()}\n`
    s += ` * ====================================================================\n */\n\n`
    s += `#include <Arduino.h>\n`
    s += `#include <Wire.h>\n`
    s += `#include <SPI.h>\n`

    if (wifi) {
      s += `\n// Optional Network Connectivity Snippets\n`
      s += `#if defined(ESP32) || defined(ESP8266)\n`
      s += `  #include <WiFi.h>\n`
      s += `  const char* WIFI_SSID     = "MyLab_WiFi";\n`
      s += `  const char* WIFI_PASSWORD = "SecretPassword123";\n`
      s += `#endif\n`
    }

    s += `\n// ── Hardware Pin Mappings ──\n`
    let pinDefs = []
    wrs.forEach((w, idx) => {
      if (w.fromPin && !w.fromPin.toLowerCase().includes('gnd') && !w.fromPin.toLowerCase().includes('vcc')) {
        const pinNum = w.fromPin.replace(/\D/g, '') || (idx + 2)
        pinDefs.push(`#define PIN_${w.fromComp?.toUpperCase().replace(/\W/g, '_') || 'DEV'}_${idx + 1} ${pinNum}`)
      }
    })
    if (pinDefs.length === 0) {
      pinDefs = [
        '#define PIN_STATUS_LED    2',
        '#define PIN_SENSOR_INPUT  34',
        '#define PIN_RELAY_OUTPUT  18',
        '#define PIN_I2C_SDA       21',
        '#define PIN_I2C_SCL       22'
      ]
    }
    s += pinDefs.join('\n') + `\n\n`

    if (i2cScan) {
      s += `// ── I2C Bus Scanner Utility ──\n`
      s += `void scanI2CDevices() {\n`
      s += `  byte error, address;\n`
      s += `  int nDevices = 0;\n`
      s += `  Serial.println("[I2C] Memulai pemindaian perangkat I2C bus...");\n`
      s += `  for (address = 1; address < 127; address++) {\n`
      s += `    Wire.beginTransmission(address);\n`
      s += `    error = Wire.endTransmission();\n`
      s += `    if (error == 0) {\n`
      s += `      Serial.print("[I2C] Ditemukan perangkat pada alamat 0x");\n`
      s += `      if (address < 16) Serial.print("0");\n`
      s += `      Serial.println(address, HEX);\n`
      s += `      nDevices++;\n`
      s += `    }\n`
      s += `  }\n`
      s += `  if (nDevices == 0) Serial.println("[I2C] Tidak ada perangkat I2C yang terdeteksi!");\n`
      s += `  else Serial.printf("[I2C] Selesai. Total %d perangkat terhubung.\\n", nDevices);\n`
      s += `}\n\n`
    }

    s += `// ── System Initialization ──\n`
    s += `void setup() {\n`
    s += `  Serial.begin(${baud});\n`
    s += `  while (!Serial && millis() < 3000) { delay(10); }\n`
    s += `  Serial.println("\\n========================================");\n`
    s += `  Serial.println("[BOOT] ${proj} Firmware Ready");\n`
    s += `  Serial.println("========================================");\n\n`
    s += `  Wire.begin();\n`

    if (i2cScan) {
      s += `  scanI2CDevices();\n`
    }

    s += `\n  // Pin Modes Initialization\n`
    s += `  pinMode(PIN_STATUS_LED, OUTPUT);\n`
    s += `  digitalWrite(PIN_STATUS_LED, LOW);\n`
    s += `}\n\n`

    s += `// ── Main Event Loop ──\n`
    s += `void loop() {\n`
    s += `  static uint32_t lastHeartbeat = 0;\n`
    s += `  if (millis() - lastHeartbeat >= 1000) {\n`
    s += `    lastHeartbeat = millis();\n`
    s += `    digitalWrite(PIN_STATUS_LED, !digitalRead(PIN_STATUS_LED));\n`
    s += `    Serial.printf("[TELEMETRY] Uptime: %lu s | Heap Free: %u bytes\\n", millis() / 1000, ESP.getFreeHeap ? ESP.getFreeHeap() : 0);\n`
    s += `  }\n`
    s += `  delay(10);\n`
    s += `}\n`

    return s
  }

  function generateEspIdfCode(proj, comps, wrs, mcu, baud, rtos) {
    let s = `/**\n * ====================================================================\n`
    s += ` * Project      : ${proj} (ESP-IDF Native C++ / FreeRTOS)\n`
    s += ` * Target Board : ${mcu.name || 'ESP32-S3 / ESP32-WROOM'}\n`
    s += ` * ====================================================================\n */\n\n`
    s += `#include <stdio.h>\n`
    s += `#include "freertos/FreeRTOS.h"\n`
    s += `#include "freertos/task.h"\n`
    s += `#include "freertos/queue.h"\n`
    s += `#include "driver/gpio.h"\n`
    s += `#include "esp_log.h"\n`
    s += `#include "esp_system.h"\n\n`
    s += `static const char *TAG = "${proj.toUpperCase()}";\n\n`
    s += `#define BLINK_GPIO GPIO_NUM_2\n\n`
    s += `// ── FreeRTOS Telemetry Task ──\n`
    s += `void vTelemetryTask(void *pvParameters) {\n`
    s += `  uint32_t counter = 0;\n`
    s += `  while (1) {\n`
    s += `    ESP_LOGI(TAG, "Heartbeat tick #%lu | Free Heap: %lu bytes", counter++, esp_get_free_heap_size());\n`
    s += `    vTaskDelay(pdMS_TO_TICKS(1000));\n`
    s += `  }\n`
    s += `}\n\n`
    s += `// ── FreeRTOS LED Actuator Task ──\n`
    s += `void vActuatorTask(void *pvParameters) {\n`
    s += `  gpio_reset_pin(BLINK_GPIO);\n`
    s += `  gpio_set_direction(BLINK_GPIO, GPIO_MODE_OUTPUT);\n`
    s += `  int level = 0;\n`
    s += `  while (1) {\n`
    s += `    gpio_set_level(BLINK_GPIO, level);\n`
    s += `    level = !level;\n`
    s += `    vTaskDelay(pdMS_TO_TICKS(500));\n`
    s += `  }\n`
    s += `}\n\n`
    s += `extern "C" void app_main(void) {\n`
    s += `  ESP_LOGI(TAG, "Starting ${proj} on ESP-IDF Core...");\n`
    s += `  xTaskCreatePinnedToCore(vTelemetryTask, "telemetry_task", 4096, NULL, 5, NULL, 0);\n`
    s += `  xTaskCreatePinnedToCore(vActuatorTask,  "actuator_task",  2048, NULL, 4, NULL, 1);\n`
    s += `}\n`
    return s
  }

  function generateMicroPythonCode(proj, comps, wrs, mcu, baud, wifi, i2cScan) {
    let s = `"""\n${proj} - MicroPython Embedded Driver\nGenerated by CircuitCraft EDA Suite\n"""\n\n`
    s += `import machine\nimport time\nimport gc\n\n`
    s += `# ── Hardware Pin Configuration ──\n`
    s += `PIN_LED = machine.Pin(2, machine.Pin.OUT)\n`
    s += `PIN_ADC = machine.ADC(machine.Pin(34))\n`
    s += `PIN_ADC.atten(machine.ADC.ATTN_11DB)\n\n`

    if (i2cScan) {
      s += `# ── I2C Bus Setup & Scanner ──\n`
      s += `i2c = machine.I2C(0, scl=machine.Pin(22), sda=machine.Pin(21), freq=400000)\n`
      s += `print("[I2C] Scanning devices on bus...")\n`
      s += `devices = i2c.scan()\n`
      s += `if devices:\n`
      s += `    for dev in devices:\n`
      s += `        print(f"[I2C] Detected peripheral at address: 0x{dev:02X}")\n`
      s += `else:\n`
      s += `    print("[I2C] No devices found.")\n\n`
    }

    s += `# ── Main Execution Loop ──\n`
    s += `print("[BOOT] ${proj} Running on MicroPython")\n`
    s += `state = 0\n\n`
    s += `while True:\n`
    s += `    state = 1 - state\n`
    s += `    PIN_LED.value(state)\n`
    s += `    analog_val = PIN_ADC.read()\n`
    s += `    voltage = (analog_val / 4095.0) * 3.3\n`
    s += `    print(f"[TELEMETRY] Sensor Raw: {analog_val} ({voltage:.2f} V) | Free RAM: {gc.mem_free()} B")\n`
    s += `    time.sleep(1)\n`
    return s
  }

  function generateRustEmbeddedCode(proj, comps, wrs, mcu, baud) {
    let s = `//! # ${proj} - Embedded Rust Firmware\n`
    s += `//! Target: no_std cortex-m / esp-hal architecture\n\n`
    s += `#![no_std]\n#![no_main]\n\n`
    s += `use panic_halt as _;\n`
    s += `use esp_backtrace as _;\n`
    s += `use esp_println::println;\n`
    s += `use esp_hal::{\n`
    s += `    clock::ClockControl,\n`
    s += `    gpio::IO,\n`
    s += `    peripherals::Peripherals,\n`
    s += `    prelude::*,\n`
    s += `    timer::TimerGroup,\n`
    s += `    Delay,\n`
    s += `};\n\n`
    s += `#[entry]\n`
    s += `fn main() -> ! {\n`
    s += `    let peripherals = Peripherals::take();\n`
    s += `    let system = peripherals.SYSTEM.split();\n`
    s += `    let clocks = ClockControl::boot_defaults(system.clock_control).freeze();\n`
    s += `    let mut delay = Delay::new(&clocks);\n\n`
    s += `    println!("[BOOT] ${proj} initialized in Embedded Rust!");\n\n`
    s += `    let io = IO::new(peripherals.GPIO, peripherals.IO_MUX);\n`
    s += `    let mut led = io.pins.gpio2.into_push_pull_output();\n\n`
    s += `    loop {\n`
    s += `        led.toggle().unwrap();\n`
    s += `        println!("[HEARTBEAT] System alive, toggling LED");\n`
    s += `        delay.delay_ms(1000u32);\n`
    s += `    }\n`
    s += `}\n`
    return s
  }

  function generatePlatformIoIni(proj, mcu, baud) {
    const isEsp32S3 = (mcu.name || '').toLowerCase().includes('s3')
    const isNano = (mcu.name || '').toLowerCase().includes('nano')
    const isUno = (mcu.name || '').toLowerCase().includes('uno')
    const isPico = (mcu.name || '').toLowerCase().includes('pico')

    let board = 'esp32dev'
    let platform = 'espressif32'
    let framework = 'arduino'

    if (isEsp32S3) {
      board = 'esp32-s3-devkitc-1'
    } else if (isNano) {
      board = 'nanoatmega328'
      platform = 'atmelavr'
    } else if (isUno) {
      board = 'uno'
      platform = 'atmelavr'
    } else if (isPico) {
      board = 'pico'
      platform = 'raspberrypi'
    }

    let s = `; PlatformIO Project Configuration File for ${proj}\n`
    s += `; Generated by CircuitCraft EDA Suite\n\n`
    s += `[platformio]\n`
    s += `default_envs = ${board}\n\n`
    s += `[env:${board}]\n`
    s += `platform = ${platform}\n`
    s += `board = ${board}\n`
    s += `framework = ${framework}\n`
    s += `monitor_speed = ${baud}\n`
    s += `upload_speed = 921600\n\n`
    s += `; Compiler & Build Flags\n`
    s += `build_flags =\n`
    s += `    -D CORE_DEBUG_LEVEL=3\n`
    s += `    -D PROJECT_NAME=\\"${proj}\\"\n\n`
    s += `; Library Dependencies\n`
    s += `lib_deps =\n`
    s += `    adafruit/Adafruit SSD1306 @ ^2.5.7\n`
    s += `    adafruit/Adafruit GFX Library @ ^1.11.5\n`
    s += `    bblanchon/ArduinoJson @ ^6.21.3\n`
    return s
  }

  function copyCode() {
    navigator.clipboard.writeText(activeCode)
    copied = true
    setTimeout(() => copied = false, 2000)
  }

  function downloadCode() {
    const extMap = {
      arduino: 'ino',
      espidf: 'cpp',
      python: 'py',
      rust: 'rs',
      platformio: 'ini',
      wokwi: 'json'
    }
    const ext = extMap[activeTab] || 'txt'
    const filename = `${projectName.toLowerCase().replace(/[^a-z0-9_]/g, '_')}.${ext}`
    const blob = new Blob([activeCode], { type: 'text/plain;charset=utf-8' })
    const url = URL.createObjectURL(blob)
    const a = document.createElement('a')
    a.href = url
    a.download = filename
    document.body.appendChild(a)
    a.click()
    document.body.removeChild(a)
    URL.revokeObjectURL(url)
  }

  function launchInSimulator() {
    try {
      const data = {
        project: projectName,
        code: activeCode
      }
      localStorage.setItem('simulator_launch_data', JSON.stringify(data))
    } catch {}
    window.open('./simulator/index.html', '_blank')
  }
