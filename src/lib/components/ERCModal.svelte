<script>
  import { createEventDispatcher } from 'svelte'

  export let show = false
  export let ercResult = { errors: [], warnings: [], info: [], totalCount: 0 }
  export let projectName = 'CircuitCraft_Diagram'

  const dispatch = createEventDispatcher()

  let activeFilter = 'all' // 'all' | 'errors' | 'warnings' | 'info' | 'matrix'
  let searchQuery = ''

  // ── Metrics & Health Score ──
  $: totalErrors = (ercResult.errors || []).length
  $: totalWarnings = (ercResult.warnings || []).length
  $: totalInfo = (ercResult.info || []).length
  $: totalIssues = (ercResult.totalCount || 0)
  $: healthScore = calculateHealthScore(totalErrors, totalWarnings)

  function calculateHealthScore(errs, warns) {
    let score = 100 - (errs * 25) - (warns * 10)
    if (score < 0) score = 0
    return score
  }

  // ── Filtered List ──
  $: filteredIssues = getFilteredIssues(ercResult, activeFilter, searchQuery)

  function getFilteredIssues(res, filter, q) {
    let items = []
    if (filter === 'all' || filter === 'errors') {
      items.push(...(res.errors || []).map(e => ({ ...e, severity: 'error' })))
    }
    if (filter === 'all' || filter === 'warnings') {
      items.push(...(res.warnings || []).map(w => ({ ...w, severity: 'warning' })))
    }
    if (filter === 'all' || filter === 'info') {
      items.push(...(res.info || []).map(i => ({ ...i, severity: 'info' })))
    }

    if (q.trim()) {
      const qLower = q.toLowerCase()
      items = items.filter(it =>
        (it.title || '').toLowerCase().includes(qLower) ||
        (it.desc || '').toLowerCase().includes(qLower) ||
        (it.compA || '').toLowerCase().includes(qLower)
      )
    }

    return items
  }

  function selectIssue(issue) {
    if (issue.wireId) {
      dispatch('selectwire', issue.wireId)
    } else if (issue.compA) {
      dispatch('selectcomp', issue.compA)
    }
    show = false
  }

  function exportErcReport() {
    let md = `# Electrical Rules Check (ERC) Audit Report: ${projectName}\n\n`
    md += `*Generated by CircuitCraft EDA Suite on ${new Date().toLocaleDateString('id-ID')}*\n\n`
    md += `### 1. Status Kesehatan Desain Skematik\n`
    md += `- **Skor Integritas Elektrikal**: ${healthScore} / 100\n`
    md += `- **Isu Kritis (Short-Circuit / Bahaya)**: ${totalErrors}\n`
    md += `- **Peringatan (Voltage Mismatch / Floating)**: ${totalWarnings}\n`
    md += `- **Catatan Rekomendasi (Best Practice)**: ${totalInfo}\n\n`

    md += `### 2. Rincian Masalah & Rekomendasi Perbaikan\n\n`
    if (totalIssues === 0) {
      md += `*Selamat! Seluruh sambungan sirkuit memenuhi standar ERC tanpa ada pelanggaran aturan kelistrikan.*\n`
    } else {
      let idx = 1
      if (ercResult.errors && ercResult.errors.length > 0) {
        md += `#### 🚨 Isu Kritis (Harus Diperbaiki Sebelum Dinyalakan)\n`
        ercResult.errors.forEach(err => {
          md += `${idx++}. **${err.title}**\n   - Deskripsi: ${err.desc}\n   - Komponen Terkait: \`${err.compA || '-'}\`\n\n`
        })
      }
      if (ercResult.warnings && ercResult.warnings.length > 0) {
        md += `#### ⚠️ Peringatan (Dapat Menyebabkan Malfungsi Logika atau Kerusakan Komponen)\n`
        ercResult.warnings.forEach(warn => {
          md += `${idx++}. **${warn.title}**\n   - Deskripsi: ${warn.desc}\n   - Komponen Terkait: \`${warn.compA || '-'}\`\n\n`
        })
      }
      if (ercResult.info && ercResult.info.length > 0) {
        md += `#### ℹ️ Catatan Desain CAD\n`
        ercResult.info.forEach(inf => {
          md += `${idx++}. **${inf.title}**\n   - Deskripsi: ${inf.desc}\n\n`
        })
      }
    }

    const blob = new Blob([md], { type: 'text/markdown;charset=utf-8' })
    const url = URL.createObjectURL(blob)
    const a = document.createElement('a')
    a.href = url
    a.download = `${projectName}_ERC_Audit.md`
    document.body.appendChild(a)
    a.click()
    document.body.removeChild(a)
    URL.revokeObjectURL(url)
  }

  function close() {
    show = false
  }
</script>

